#!/usr/bin/env bash
# Allow HTTPS (443) only from Cloudflare's published address ranges, and let nginx see the
# visitor's real address from the CF-Connecting-IP header for those ranges only.
# Run again whenever Cloudflare changes its ranges (rarely). Other UFW rules are untouched.
set -euo pipefail
SYSTEMCTL="${SYSTEMCTL:-systemctl}"
REALIP=/etc/nginx/conf.d/cloudflare-realip.conf

ranges="$(curl -fsS https://www.cloudflare.com/ips-v4; echo; curl -fsS https://www.cloudflare.com/ips-v6)"
ranges="$(printf '%s\n' "$ranges" | grep -E '^[0-9a-fA-F:.]+/[0-9]{1,3}$' || true)"
[ "$(printf '%s\n' "$ranges" | grep -c /)" -ge 10 ] || { echo "Could not fetch Cloudflare's ranges" >&2; exit 1; }

{
    echo "# Generated by deploy/staging/cloudflare-ips.sh: Cloudflare's ranges ($(date -u +%F))."
    printf '%s\n' "$ranges" | sed 's/^/set_real_ip_from /; s/$/;/'
    echo "real_ip_header CF-Connecting-IP;"
} >"$REALIP"
nginx -t -q
$SYSTEMCTL reload nginx

if ufw status | grep '^Status: active' >/dev/null; then  # not -q: see pipefail
    # Remove the previous Cloudflare rules (highest number first), then add the current ones.
    # (grep finds nothing on the first run, which must not stop the script.)
    { ufw status numbered | grep '# cloudflare' || true; } | sed -E 's/^\[ *([0-9]+)\].*/\1/' |
        sort -rn | while read -r n; do ufw --force delete "$n" >/dev/null; done
    printf '%s\n' "$ranges" | while read -r cidr; do
        ufw allow proto tcp from "$cidr" to any port 443 comment cloudflare >/dev/null
    done
    echo "UFW: port 443 allowed from $(ufw status | grep -c '# cloudflare') Cloudflare rules."
else
    echo "WARNING: UFW is not active. Enable it after allowing your SSH port," \
        "then run this script again." >&2
fi
